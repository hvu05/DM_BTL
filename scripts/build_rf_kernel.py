#!/usr/bin/env python3
"""Build kaggle_kernel_rf/main.py: a self-contained Kaggle kernel for Random Forest.

Re-uses the preprocessing part of kaggle_kernel/main.py (embedded clean manifest, resize,
split, HOG) verbatim so Random Forest is evaluated on exactly the same split as the SVM kernel,
then appends the RF CORE section of scripts/train_rf.py.

    python scripts/build_rf_kernel.py
"""
from __future__ import annotations

import json
from pathlib import Path

SVM_KERNEL = Path("kaggle_kernel/main.py")
RF_SCRIPT = Path("scripts/train_rf.py")
OUT_DIR = Path("kaggle_kernel_rf")

MAIN = '''

def main() -> int:
    t_start = time.time()
    work_dir = Path("/kaggle/working")
    raw_root = find_raw_dataset_root()

    manifest_file = unpack_clean_manifest(work_dir / "clean_manifest.csv")
    dataset_dir = work_dir / "dataset"
    output_dir = work_dir / "outputs" / "rf"

    print("Step 1/4: Resizing images (direct & padding)...")
    build_resized_branches(raw_root, manifest_file, dataset_dir)

    print("Step 2/4: Creating stratified 4/1/1 split (same as SVM kernel)...")
    split_file = dataset_dir / "split.csv"
    create_split(manifest_file, split_file, seed=42)
    output_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy(split_file, output_dir / "split_used.csv")

    print("Step 3/4: Extracting HOG features...")
    extract_hog_branch("direct", dataset_dir, split_file)
    extract_hog_branch("padding", dataset_dir, split_file)

    print("Step 4/4: Random Forest (5-fold CV tuning + test evaluation)...")
    train_and_eval_rf(dataset_dir / "features", output_dir)

    print("Cleaning up large intermediate files...")
    shutil.rmtree(dataset_dir, ignore_errors=True)
    manifest_file.unlink(missing_ok=True)

    print(f"Pipeline finished successfully in {(time.time() - t_start) / 60:.2f} minutes!")
    print(f"Download the folder: {output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def main() -> int:
    svm_src = SVM_KERNEL.read_text(encoding="utf-8")
    cut = svm_src.index("def train_and_eval_svm(")
    preprocessing = svm_src[:cut].replace(
        '"""End-to-end reproducible SOHAS preprocessing and SVM benchmarking pipeline for Kaggle."""',
        '"""End-to-end SOHAS preprocessing + Random Forest pipeline for Kaggle '
        '(auto-generated by scripts/build_rf_kernel.py; do not edit by hand)."""',
        1,
    )
    model_src = RF_SCRIPT.read_text(encoding="utf-8")
    begin, end = "# --- BEGIN RF CORE ---", "# --- END RF CORE ---"
    core = model_src[model_src.index(begin): model_src.index(end) + len(end)]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "main.py").write_text(preprocessing.rstrip() + "\n\n\n" + core + "\n" + MAIN, encoding="utf-8")
    meta = json.loads((SVM_KERNEL.parent / "kernel-metadata.json").read_text(encoding="utf-8"))
    meta.update({"id": "YOUR_KAGGLE_USERNAME/sohas-rf-pipeline", "title": "sohas-rf-pipeline"})
    (OUT_DIR / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_DIR / 'main.py'} and {OUT_DIR / 'kernel-metadata.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
